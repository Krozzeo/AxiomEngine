import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const metadata=JSON.parse(await readFile(new URL('protocol/schema/script-bindings.json',root),'utf8'));
const components=await Promise.all(metadata.components.map(path=>readFile(new URL('protocol/schema/'+path,root),'utf8').then(JSON.parse)));
const types={vec3:'Vec3',quat:'Quat'};
const code=['// Generated by scripts/generate-script-bindings.mjs. Do not edit.', 'using System.Text.Json;',`namespace ${metadata.namespace};`];
for(const component of components) {
 const properties=component.properties;
 if(properties.some(p=>!types[p.type]))throw new Error('Unsupported script component property');
 code.push(`public readonly record struct ${component.name}(${properties.map(p=>types[p.type]+' '+p.name[0].toUpperCase()+p.name.slice(1)).join(', ')}) {`);
 code.push(` internal static ${component.name} Read(JsonElement value) => new(${properties.map(p=>types[p.type]+'.Read(value.GetProperty("'+p.name+'"))').join(', ')});`);
 code.push('}');
}
code.push('internal static class Limits {');
for(const [key,value]of Object.entries(metadata.limits))code.push(` internal const int ${key[0].toUpperCase()+key.slice(1)} = ${value};`);
code.push('}');
const files=new Map([['engine/scripting/templates/GeneratedComponents.cs',code.join('\n')+'\n'],['engine/scripting/contract.mjs','// Generated from protocol/schema/script-bindings.json.\nexport const SCRIPT_CONTRACT = Object.freeze('+JSON.stringify({version:metadata.schemaVersion,...metadata.limits})+');\n']]);
for(const [name,content]of files){const path=new URL(name,root);if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==content)throw new Error('Stale generated bindings: '+name);}else await writeFile(path,content);}
